inline void buildTable(
    const uint8_t* bits,       
    const uint8_t* vals,       
    int            valsCount,  
    std::unordered_map<uint8_t, HuffmanCode>& table)
{

    uint32_t code = 0;
    int pos = 0;

    for (int length = 1; length <= 16; length++) {
        for (int i = 0; i < bits[length]; i++) {
            assert(pos < valsCount && "buildTable: pos exceeded valsCount — malformed bits[] array");
            table[vals[pos]] = { static_cast<uint16_t>(code), static_cast<uint8_t>(length) };
            code++;
            pos++;
        }
        code <<= 1;
    }
}


inline std::unordered_map<uint8_t, HuffmanCode>& getLumaDCTable() {
    static std::unordered_map<uint8_t, HuffmanCode> table;
    if (table.empty()) buildTable(dc_luma_bits, dc_luma_vals, 12, table);
    return table;
}

inline std::unordered_map<uint8_t, HuffmanCode>& getChromaDCTable() {
    static std::unordered_map<uint8_t, HuffmanCode> table;
    if (table.empty()) buildTable(dc_chroma_bits, dc_chroma_vals, 12, table);
    return table;
}

inline std::unordered_map<uint8_t, HuffmanCode>& getLumaACTable() {
    static std::unordered_map<uint8_t, HuffmanCode> table;
    if (table.empty()) buildTable(ac_luma_bits, ac_luma_vals, 162, table);
    return table;
}

inline std::unordered_map<uint8_t, HuffmanCode>& getChromaACTable() {
    static std::unordered_map<uint8_t, HuffmanCode> table;
    if (table.empty()) buildTable(ac_chroma_bits, ac_chroma_vals, 162, table);
    return table;
}

inline void initHuffmanTables() {
    getLumaDCTable();
    getChromaDCTable();
    getLumaACTable();
    getChromaACTable();
}

inline LeftAlignedPrefix buildSentinelPrefix(
    const std::unordered_map<uint8_t, HuffmanCode>& table,
    uint8_t key)
{
    const HuffmanCode& found = table.at(key);

    uint32_t sentinelBit       = static_cast<uint32_t>(1) << found.length;
    uint32_t chunkWithSentinel = static_cast<uint32_t>(found.code) | sentinelBit;

    uint8_t totalBits     = found.length + 1;
    uint8_t trailingZeros = static_cast<uint8_t>(32 - totalBits);

    return { chunkWithSentinel << trailingZeros, trailingZeros };
}



inline LeftAlignedPrefix getLumaDCPrefix(uint8_t category) {
    if (category > 11)
        throw std::out_of_range("getLumaDCPrefix: category must be 0-11, got " + std::to_string(category));
    return buildSentinelPrefix(getLumaDCTable(), category);
}

inline LeftAlignedPrefix getChromaDCPrefix(uint8_t category) {
    if (category > 11)
        throw std::out_of_range("getChromaDCPrefix: category must be 0-11, got " + std::to_string(category));
    return buildSentinelPrefix(getChromaDCTable(), category);
}

inline LeftAlignedPrefix getLumaACPrefix(uint8_t run, uint8_t size) {
    if (run > 15 || size > 15)
        throw std::out_of_range(
            "getLumaACPrefix: run and size must each be 0-15, got run=" +
            std::to_string(run) + " size=" + std::to_string(size));
    uint8_t tag = static_cast<uint8_t>((run << 4) | size);
    return buildSentinelPrefix(getLumaACTable(), tag);
}

inline LeftAlignedPrefix getChromaACPrefix(uint8_t run, uint8_t size) {
    if (run > 15 || size > 15)
        throw std::out_of_range(
            "getChromaACPrefix: run and size must each be 0-15, got run=" +
            std::to_string(run) + " size=" + std::to_string(size));
    uint8_t tag = static_cast<uint8_t>((run << 4) | size);
    return buildSentinelPrefix(getChromaACTable(), tag);
}

